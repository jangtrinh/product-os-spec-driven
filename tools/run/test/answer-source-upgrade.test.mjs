import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {loadConfig} from '../../lib/config/config-loader.mjs';
import {hasKitHistory} from './kit-history.mjs';
const kit = fileURLToPath(new URL('../../../', import.meta.url));
test('answer source upgrade preserves owner context additions, existing answers and dry-run bytes', t => {
 if (!hasKitHistory(t, kit, '14ddee3')) return;
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'answers-upgrade-')); t.after(() => fs.rmSync(scratch, {recursive: true, force: true}));
  const old = path.join(scratch, 'baseline-kit'), project = path.join(scratch, 'project'); fs.mkdirSync(old);
  const archive = spawnSync('git', ['archive', '14ddee3', 'SPEC.md', 'format', 'templates', 'rules', 'prompts', 'tools', 'evals', 'config'], {cwd: kit, maxBuffer: 100 * 1024 * 1024}); assert.equal(archive.status, 0);
  assert.equal(spawnSync('tar', ['-x', '-C', old], {input: archive.stdout}).status, 0);
  const call = (source, args) => spawnSync(process.execPath, [path.join(source, 'tools/run/init.mjs'), '--project', project, ...args], {encoding: 'utf8'});
  let r = call(old, ['--name', 'Owner project', '--lang', 'en']); assert.equal(r.status, 0, r.stdout + r.stderr);
  const cfg = path.join(project, 'config/pipeline.yaml');
  fs.writeFileSync(cfg, fs.readFileSync(cfg, 'utf8').replace('      - templates/clarify-record.md', '      - templates/clarify-record.md\n      - context/owner.md'));
  fs.writeFileSync(path.join(project, 'context/owner.md'), 'Owner context.\n');
  const answers = '# PO source\n\n| Q | Answer | Decided by | Date | Note |\n|---|---|---|---|---|\n| Q-001 | Keep original bytes | po@example.test | 2026-10-13 | Existing answer |\n';
  fs.writeFileSync(path.join(project, 'input/answers.md'), answers);
  const beforeConfig = fs.readFileSync(cfg), beforeLock = fs.readFileSync(path.join(project, 'kit.lock.json'));
  r = call(kit, ['--upgrade', '--dry-run']); assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.deepEqual(fs.readFileSync(cfg), beforeConfig); assert.deepEqual(fs.readFileSync(path.join(project, 'kit.lock.json')), beforeLock);
  r = call(kit, ['--upgrade']); assert.equal(r.status, 0, r.stdout + r.stderr);
  const config = loadConfig(project); assert.ok(config.stages.clarify.context.includes('context/owner.md')); assert.ok(config.stages.clarify.context.includes('input/answers.md'));
  assert.equal(fs.readFileSync(path.join(project, 'input/answers.md'), 'utf8'), answers);
  assert.equal(call(kit, ['--upgrade']).status, 0);
});
